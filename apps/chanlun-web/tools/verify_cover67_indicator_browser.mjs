// Run against an isolated browser profile/origin; never clears existing annotation storage.
import assert from 'node:assert/strict';
const origin=process.env.COVER67_TEST_URL||'http://127.0.0.1:8878';
const port=process.env.CDP_PORT||'9337';
const pages=await(await fetch(`http://127.0.0.1:${port}/json/list`)).json();
const page=pages.find(p=>p.type==='page'&&(p.url==='about:blank'||p.url.startsWith(origin)));
assert.ok(page,'isolated test tab');
const ws=new WebSocket(page.webSocketDebuggerUrl);await new Promise((ok,bad)=>{ws.onopen=ok;ws.onerror=bad;});
let id=0;const pending=new Map(),errors=[];
ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result);}else if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails.exception?.description||m.params.exceptionDetails.text);};
const call=(method,params={})=>new Promise((resolve,reject)=>{const n=++id;pending.set(n,{resolve,reject});ws.send(JSON.stringify({id:n,method,params}));});
const ev=async expression=>{const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
const until=async expr=>{for(let n=0;n<150;n++){if(await ev(expr))return;await new Promise(r=>setTimeout(r,200));}throw Error('timeout '+expr);};
try {
 await call('Runtime.enable'); await call('Page.enable');
 await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await call('Page.navigate',{url:origin+'/index.html'});
 await until('window.__INIT_OK===true && typeof cover67IndicatorRefresh === "function"');
 await ev('cover67IndicatorEnable(false)');
 assert.equal(await ev('document.getElementById("indicatorToggle").previousElementSibling.textContent'),'指标');
 await ev('document.getElementById("cover67IndicatorToggle").click()');
 assert.equal(await ev('cover67IndicatorMarkers(activeView).length'),181);
 assert.equal(await ev('ANN.on'),false,'normal chart indicator independent of annotations');
 await ev('document.getElementById("cover67IndicatorList").click()');
 assert.equal(await ev('document.querySelectorAll(".c67-entry").length'),181);
 await ev('document.querySelector(".c67-entry").click()');
 const first=await ev('COVER67_INDICATOR.time');
 await ev('document.getElementById("cover67IndicatorNext").click()');
 assert.ok(await ev('COVER67_INDICATOR.time')>first);
 await ev('document.getElementById("cover67IndicatorPrev").click()');
 assert.equal(await ev('COVER67_INDICATOR.time'),first);
 await ev('switchSymbol("ETH")'); await until('currentSym==="ETH"');
 assert.equal(await ev('COVER67_INDICATOR.rows.length'),170);
 assert.equal(await ev('document.querySelectorAll(".c67-entry").length'),170);
 assert.ok((await ev('document.getElementById("cover67IndicatorTitle").textContent')).includes('ETH 1D'));
 await ev('document.querySelector(".c67-entry").click()');
 await ev('document.getElementById("cover67IndicatorReview").click()');
 assert.equal(await ev('ANN.on'),true);
 assert.equal(await ev('COVER67_INDICATOR.open'),false);
 assert.ok(await ev('cover67IndicatorMarkers(activeView).every(m=>m.time<=candlesFor("raw")[ANN.sigs[ANN.idx].i].time)'),'no markers beyond blind cutoff');
 await ev('annSetOpen(false); document.getElementById("cover67IndicatorList").click()');
 await ev("Array.from(document.querySelectorAll(\"#tfToggle button\")).find(b=>b.dataset.tf===\"4H\").click()");
 await until('activeTF==="4H"');
 assert.equal(await ev('COVER67_INDICATOR.rows.length'),await ev('annCoverContext().signals.length'));
 assert.ok((await ev('document.getElementById("cover67IndicatorTitle").textContent')).includes('ETH 4H'));
 await ev("Array.from(document.querySelectorAll(\"#tfToggle button\")).find(b=>b.dataset.tf===\"1D\").click()");
 await ev("Array.from(document.querySelectorAll(\"#viewToggle button\")).find(b=>b.dataset.view===\"merged\").click()");
 assert.ok(await ev('cover67IndicatorMarkers(activeView).every(m=>candlesFor(activeView).some(c=>c.time===m.time))'));
 await ev("Array.from(document.querySelectorAll(\"#viewToggle button\")).find(b=>b.dataset.view===\"raw\").click()");
 await ev('switchSymbol("NVDA")'); await until('currentSym==="NVDA"');
 assert.equal(await ev('COVER67_INDICATOR.rows.length'),await ev('annCoverContext().signals.length'));
 assert.ok((await ev('document.getElementById("cover67IndicatorTitle").textContent')).includes('NVDA'));
 await ev('document.getElementById("cover67IndicatorToggle").click()');
 assert.equal(await ev('cover67IndicatorMarkers(activeView).length'),0);
 assert.equal(await ev('document.getElementById("cover67IndicatorPanel").hidden'),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: toolbar placement, 181 BTC / 170 ETH markers, list navigation, asset/timeframe switches, annotation handoff, blind cutoff, toggle cleanup');
} finally {ws.close();}
